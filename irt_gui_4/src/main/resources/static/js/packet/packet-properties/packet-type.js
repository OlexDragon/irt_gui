
import { createIdMap } from './helper/id-map.mjs'

const groupId = createIdMap({
    spontaneous: 0x0,			/* Spontaneous message, generated by device. */
    response: 0x1,			/* Response, generated as response to command or status request. */
    request: 0x2,			/* Status request. */
    command: 0x3,			/* Command. */
    error: 0xFE,			/* Error Packet. */
    acknowledgement: 0xFF			/* Layer 2 acknowledgement. */
});

export const id = groupId.id;				// id(name)
export const name = groupId.name;			// name(code)
export const toString = groupId.toString;	// `${name} (${code})`
export const info = groupId.info;			// name: {code: code, name: name}

export default groupId.map;					// name: code
